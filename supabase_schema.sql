CREATE TABLE IF NOT EXISTS public.usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT UNIQUE NOT NULL,
    nome TEXT NOT NULL,
    senha_hash TEXT NOT NULL,
    perfil TEXT NOT NULL DEFAULT 'operadora',
    ativo INTEGER NOT NULL DEFAULT 1,
    criado_em TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.cartoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero INTEGER NOT NULL,
    grupo INTEGER NOT NULL DEFAULT 1,
    saldo_inicial_centavos INTEGER NOT NULL,
    saldo_centavos INTEGER NOT NULL,
    data_inicio TEXT DEFAULT '',
    data_fim TEXT DEFAULT '',
    nome TEXT DEFAULT '',
    observacao TEXT DEFAULT '',
    atualizado_em TEXT DEFAULT ''
);

CREATE INDEX IF NOT EXISTS idx_cartoes_numero ON public.cartoes(numero);
CREATE INDEX IF NOT EXISTS idx_cartoes_nome ON public.cartoes(nome);
CREATE INDEX IF NOT EXISTS idx_cartoes_saldo ON public.cartoes(saldo_centavos);

CREATE TABLE IF NOT EXISTS public.movimentacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cartao_id BIGINT NOT NULL REFERENCES public.cartoes(id) ON DELETE CASCADE,
    cartao_numero INTEGER NOT NULL,
    usuario_id BIGINT NOT NULL REFERENCES public.usuarios(id),
    usuario_nome TEXT NOT NULL,
    tipo TEXT NOT NULL,
    valor_estadia_centavos INTEGER NOT NULL,
    valor_descontado_centavos INTEGER NOT NULL,
    valor_complemento_caixa_centavos INTEGER NOT NULL DEFAULT 0,
    saldo_anterior_centavos INTEGER NOT NULL,
    saldo_posterior_centavos INTEGER NOT NULL,
    observacao TEXT DEFAULT '',
    estornado INTEGER NOT NULL DEFAULT 0,
    estornado_por_nome TEXT DEFAULT '',
    estornado_em TEXT DEFAULT '',
    criado_em TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_mov_cartao_id ON public.movimentacoes(cartao_id);
CREATE INDEX IF NOT EXISTS idx_mov_cartao_num ON public.movimentacoes(cartao_numero);
CREATE INDEX IF NOT EXISTS idx_mov_criado_em ON public.movimentacoes(criado_em);

-- Função RPC para cálculo instantâneo dos KPIs do Painel no Supabase
CREATE OR REPLACE FUNCTION public.obter_resumo_caixa(p_hoje TEXT, p_usuario_id BIGINT)
RETURNS JSON
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_total_cartoes BIGINT;
    v_cartoes_com_saldo BIGINT;
    v_cartoes_zerados BIGINT;
    v_saldo_inicial_total BIGINT;
    v_saldo_atual_total BIGINT;
    v_atendimentos_hoje BIGINT;
    v_descontado_hoje BIGINT;
    v_complemento_hoje BIGINT;
    v_meus_atendimentos BIGINT;
    v_meu_descontado BIGINT;
    v_meu_complemento BIGINT;
BEGIN
    SELECT
        COUNT(*),
        COALESCE(SUM(CASE WHEN saldo_centavos > 0 THEN 1 ELSE 0 END), 0),
        COALESCE(SUM(CASE WHEN saldo_centavos = 0 THEN 1 ELSE 0 END), 0),
        COALESCE(SUM(saldo_inicial_centavos), 0),
        COALESCE(SUM(saldo_centavos), 0)
    INTO
        v_total_cartoes,
        v_cartoes_com_saldo,
        v_cartoes_zerados,
        v_saldo_inicial_total,
        v_saldo_atual_total
    FROM public.cartoes;

    SELECT
        COUNT(*),
        COALESCE(SUM(valor_descontado_centavos), 0),
        COALESCE(SUM(valor_complemento_caixa_centavos), 0)
    INTO
        v_atendimentos_hoje,
        v_descontado_hoje,
        v_complemento_hoje
    FROM public.movimentacoes
    WHERE criado_em LIKE (p_hoje || '%')
      AND tipo IN ('BAIXA_TOTAL', 'BAIXA_PARCIAL')
      AND estornado = 0;

    SELECT
        COUNT(*),
        COALESCE(SUM(valor_descontado_centavos), 0),
        COALESCE(SUM(valor_complemento_caixa_centavos), 0)
    INTO
        v_meus_atendimentos,
        v_meu_descontado,
        v_meu_complemento
    FROM public.movimentacoes
    WHERE criado_em LIKE (p_hoje || '%')
      AND usuario_id = p_usuario_id
      AND tipo IN ('BAIXA_TOTAL', 'BAIXA_PARCIAL')
      AND estornado = 0;

    RETURN json_build_object(
        'total_cartoes', v_total_cartoes,
        'cartoes_com_saldo', v_cartoes_com_saldo,
        'cartoes_zerados', v_cartoes_zerados,
        'saldo_inicial_total', ROUND(v_saldo_inicial_total / 100.0, 2),
        'saldo_atual_total', ROUND(v_saldo_atual_total / 100.0, 2),
        'total_ja_utilizado', ROUND((v_saldo_inicial_total - v_saldo_atual_total) / 100.0, 2),
        'atendimentos_hoje', v_atendimentos_hoje,
        'descontado_hoje', ROUND(v_descontado_hoje / 100.0, 2),
        'complemento_caixa_hoje', ROUND(v_complemento_hoje / 100.0, 2),
        'meus_atendimentos_hoje', v_meus_atendimentos,
        'meu_descontado_hoje', ROUND(v_meu_descontado / 100.0, 2),
        'meu_complemento_hoje', ROUND(v_meu_complemento / 100.0, 2)
    );
END;
$$;
